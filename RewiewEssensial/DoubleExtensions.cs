using System;
using System.Collections.Generic;
using System.Text;

namespace RewiewEssensial
{
    public static class DoubleExtensions
    {
        public static double Add(this double a, double b)
        {
            return a + b;
        }


        public static double Subtract(this double a, double b)
        {
            return a - b;
        }
    }
}
